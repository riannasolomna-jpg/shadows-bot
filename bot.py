def looks_like_spam(text):

    clean = re.sub(
        r"\s+",
        "",
        text
    )

    if len(clean) < 20:
        return True

    # Один символ повторяется почти весь текст
    if len(set(clean)) <= 3 and len(clean) >= 30:
        return True

    # Слишком много одинаковых символов подряд
    if re.search(
        r"(.)\1{20,}",
        clean
    ):
        return True

    return False


