# ============================================================

def split_text(
    text,
    limit=3900
):

    parts = []

    while len(text) > limit:

        cut = text.rfind(
            "\n",
            0,
            limit
        )

        if cut < 500:
            cut = limit

        parts.append(
            text[:cut]
        )

        text = text[cut:].lstrip()

    if text:
        parts.append(
            text
        )

    return parts


