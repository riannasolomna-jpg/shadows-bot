@bot.callback_query_handler(
    func=lambda call:
        call.data.startswith(
            (
                "accept_",
                "reject_",
                "reply_"
            )
        )
)
def handle_admin_action(call):

    if call.from_user.id != ADMIN_ID:

        bot.answer_callback_query(
            call.id,
            "У вас нет прав администратора."
        )

        return

    action, target_chat_id = call.data.split(
        "_",
        1
    )

    target_chat_id = int(
        target_chat_id
    )

    bot.answer_callback_query(
        call.id
    )

    # ========================================================
    # ПРИНЯТЬ
    # ========================================================

    if action == "accept":

        bot.send_message(
            target_chat_id,
            "🎉 Ваша анкета успешно принята администрацией!\n\n"
            "Поздравляем!"
        )

        try:

            bot.edit_message_text(
                call.message.text
                + "\n\n"
                + "✅ ПРИНЯТО АДМИНИСТРАТОРОМ",

                chat_id=ADMIN_ID,
                message_id=call.message.message_id
            )

        except Exception as e:

            print(
                f"Ошибка изменения сообщения: {e}"
            )
            # ========================================================
    # ОТКЛОНИТЬ
    # ========================================================

    elif action == "reject":

        bot.send_message(
            target_chat_id,
            "❌ К сожалению, ваша анкета "
            "была отклонена администрацией.\n\n"
            "Для уточнения деталей обратитесь "
            "к @CrazyCrabSalad."
        )

        try:

            bot.edit_message_text(
                call.message.text
                + "\n\n"
                + "❌ ОТКЛОНЕНО АДМИНИСТРАТОРОМ",

                chat_id=ADMIN_ID,
                message_id=call.message.message_id
            )

        except Exception as e:

            print(
                f"Ошибка изменения сообщения: {e}"
            )

    # ========================================================
    # ОТВЕТИТЬ
    # ========================================================

    elif action == "reply":

        msg = bot.send_message(
            ADMIN_ID,
            f"Введите ответ для пользователя {target_chat_id}:"
        )

        bot.register_next_step_handler(
            msg,
            send_reply_to_user,
            target_chat_id
        )


