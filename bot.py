@bot.message_handler(
    func=lambda msg:
        user_states.get(
            msg.chat.id,
            {}
        ).get("step") == "waiting_anketa"
)
def receive_anketa_part(message):

    chat_id = message.chat.id

    if not message.text:

        bot.send_message(
            chat_id,
            "⚠️ Анкету пока необходимо отправлять текстом."
        )

        return

    text = message.text.strip()

    if not text:
        return

    state = user_states.get(
        chat_id
    )

    if not state:
        return

    # Сохраняем информацию о пользователе
    state["username"] = message.from_user.username
    state["full_name"] = message.from_user.full_name

    # Добавляем часть анкеты
    state["messages"].append(
        text
    )

    # Останавливаем старый таймер
    old_timer = user_timers.get(
        chat_id
    )

    if old_timer:

        try:
            old_timer.cancel()
        except Exception:
            pass

    # Запускаем новый таймер
    timer = threading.Timer(
        BUFFER_SECONDS,
        process_anketa,
        args=(chat_id,)
    )

    timer.daemon = True

    user_timers[chat_id] = timer

    timer.start()

    count = len(
        state["messages"]
    )

    bot.send_message(
        chat_id,
        f"📥 Получена часть анкеты №{count}.\n"
        "Если есть продолжение — отправляйте его следующим сообщением.\n\n"
        "⏳ После последней части подождите 30 секунд."
    )


