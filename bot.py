def analyze_anketa_with_ai(
    text,
    category
):

    if not client:

        return (
            False,
            "ОШИБКА ИИ: GROQ_API_KEY не настроен."
        )

    prompt = (
        SYSTEM_PROMPT
        + "\n\n"
        + "ВЫБРАННАЯ ПОЛЬЗОВАТЕЛЕМ КАТЕГОРИЯ:\n"
        + category
        + "\n\n"
        + "ТЕКСТ АНКЕТЫ:\n"
        + "====================\n"
        + text
        + "\n====================\n"
    )

    try:

        response = client.chat.completions.create(
            model="llama-3.3-70b-versatile",
            messages=[
                {
                    "role": "user",
                    "content": prompt
                }
            ],
            temperature=0.1,
            max_tokens=1800
        )

        result = response.choices[
            0
        ].message.content

        if not result:

            return (
                False,
                "ОШИБКА ИИ: получен пустой ответ."
            )

        # Нормализуем пробелы только для проверки статуса
        normalized = result.upper().replace(
            " ",
            ""
        )

        if "СТАТУС:ПРИНЯТЬ" in normalized:

            return (
                True,
                result
            )

        if "СТАТУС:ТРЕБУЕТПРАВОК" in normalized:

            return (
                False,
                result
            )

        # Если ИИ нарушил формат,
        # лучше остановить процесс, чем случайно
        # отправить сомнительную анкету админу.
        return (
            False,
            "ОШИБКА ИИ: модель вернула ответ "
            "в неправильном формате."
        )

    except Exception as e:

        error = (
            f"ОШИБКА ИИ: {repr(e)}"
        )

        print(error)

        return (
            False,
            error
        )

