def send_long_message(
    chat_id,
    text,
    reply_markup=None
):

    parts = split_text(
        text
    )

    for index, part in enumerate(parts):

        if index == len(parts) - 1:

            bot.send_message(
                chat_id,
                part,
                reply_markup=reply_markup
            )

        else:

            bot.send_message(
                chat_id,
                part
            )
